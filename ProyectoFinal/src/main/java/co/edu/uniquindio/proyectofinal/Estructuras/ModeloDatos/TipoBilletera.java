
package co.edu.uniquindio.proyectofinal.Estructuras.ModeloDatos;

/**
 * Define las categorías de billeteras disponibles en el sistema Fintech.
 *
 * Cada valor representa una finalidad de administración del dinero.
 *
 * @author Proyecto Fintech
 * @version 1.0
 */
public enum TipoBilletera {

    /** Billetera destinada al ahorro. */
    AHORRO,

    /** Billetera para gastos cotidianos. */
    GASTO_DIARIO,

    /** Billetera destinada a compras. */
    COMPRAS,

    /** Billetera destinada a gastos de transporte. */
    TRANSPORTE,

    /** Billetera destinada a administrar inversiones. */
    INVERSION
}


package co.edu.uniquindio.proyectofinal.Estructuras.ModeloDatos;

/**
 * Define la periodicidad de ejecución de una operación programada.
 *
 * @author Proyecto Fintech
 * @version 1.0
 */
public enum Frecuencia {

    /** La operación se ejecuta una sola vez. */
    UNICA,

    /** La operación se repite cada semana. */
    SEMANAL,

    /** La operación se repite cada mes. */
    MENSUAL
}
